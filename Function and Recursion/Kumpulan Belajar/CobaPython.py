#Program untuk menghitung luas & keliling

print("Masukkan nilai rusuk untuk balok Anda:")
p = int(input("Nilai panjang: "))
l = int(input("Nilai lebar: "))
t = int(input("Nilai tinggi: "))

luas = p * l * t
keliling = p * l * 6
print("")
print("Nilai luas: ", luas)
print("Nilai keliling: ", keliling)





